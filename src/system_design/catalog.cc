std::string StageKindName(StageKind kind) {
  switch (kind) {
    case StageKind::kRequirements:
      return "requirements";
    case StageKind::kEstimation:
      return "estimation";
    case StageKind::kContract:
      return "contract";
    case StageKind::kDataModel:
      return "data_model";
    case StageKind::kArchitecture:
      return "architecture";
    case StageKind::kTradeoffs:
      return "tradeoffs";
  }
  throw std::invalid_argument("unknown System Design stage kind");
}

